// The offsets in PCF_DATA of the lengths, the resolutions and the steps.
static const uint32_t LENGTHS = 0;
static const uint32_t RESOLUTIONS = 0x10033380u - 0x10033310u;
static const uint32_t STEPS = 0x100333F0u - 0x10033310u;

// The envelope and cutoff (every 4 samples) in double in every build, soft-double on the FM-1:
// in float the envelope's rounding moves it across coefficient-table indices. The per-sample
// filter (`real`) is not sensitive.
typedef double ctl;

static const ctl ONE = (ctl)1;                    // dbl_10152288
static const float ZERO = 0.0f;                   // flt_10152294
static const float FREQ_SCALE = 512.0f;           // flt_10152298
static const float FREQ_SCALE2 = 0.0078125f;      // flt_1015229C, 0x3C000000
static const float TOP = 511.0f;                  // flt_101522A0, 0x43FF8000
static const float SLOW_KEEP = 0.995f;            // flt_101522A4, 0x3F7EB852
static const float SLOW_TAKE = 0.0049999952f;     // flt_101522A8, 0x3BA3D700
static const float INSTANT_TAKE = 1.0f;           // flt_101522AC
static const float METER_DECAY = 0.92f;           // flt_1015227C, 0x3F6B851F
static const float METER_SCALE = 127.0f;          // flt_10152280

const uint8_t Pcf::DEFAULTS[Pcf::PARAMS] = {1, 70, 64, 40, 24, 90, 1, 0};

// |x| as 0x1001671D takes it: -0.0 stays -0.0.
static inline float abs_bits(float x) { return bits(x) > 0x80000000u ? -x : x; }

static inline uint16_t data_u16(uint32_t o)
{
    return (uint16_t)(PCF_DATA[o] | (PCF_DATA[o + 1] << 8));
}

static inline uint32_t clamp_wave(uint8_t x) { return x < 127 ? x : 127u; }

// pcf::pattern: the length and resolution of `wave`.
static inline void pattern_of(uint8_t wave, uint16_t* len, uint16_t* res)
{
    uint32_t w = clamp_wave(wave);
    *len = data_u16(LENGTHS + 2 * w);
    *res = data_u16(RESOLUTIONS + 2 * w);
}

// pcf::velocity: the step velocity, 0 outside PCF_DATA.
static inline uint8_t velocity(uint8_t wave, int32_t step)
{
    int64_t i = (int64_t)STEPS + (int64_t)clamp_wave(wave) * 32 + (int64_t)step;
    if (i < 0 || i >= (int64_t)PCF_DATA_LEN) return 0;
    return PCF_DATA[i];
}

// pcf::quotient: false for a resolution other than 32, 16 or 8.
static inline bool quotient_of(int32_t tick, uint16_t res, int32_t* q)
{
    switch (res) {
    case 32: *q = tick / 24; return true;
    case 16: *q = tick / 48; return true;
    case 8: *q = tick / 96; return true;
    default: return false;
    }
}

static inline ctl smooth_cutoff(const Smoother& k, uint8_t freq, float y1, float y2)
{
    ctl f = (((ctl)freq * (ctl)FREQ_SCALE) * (ctl)FREQ_SCALE2) * (ctl)k.g;
    return ((ctl)k.a * (ctl)y1 + f) - (ctl)k.b2 * (ctl)y2;
}

static inline ctl trigger_level(uint8_t v, uint8_t amount, float base)
{
    ctl raw = (ctl)(((int32_t)v * (int32_t)amount) >> 5);
    if (raw + (ctl)base > (ctl)TOP) return (ctl)TOP - (ctl)base;
    return raw;
}

static inline int32_t env_index(ctl env)
{
    ctl v;
    if (env < (ctl)ZERO || env != env)
        v = (ctl)ZERO;
    else if (env > (ctl)TOP)
        v = (ctl)TOP;
    else
        v = env;
    return (int32_t)v;  // as_i32: v is 0..511
}

namespace {

struct Envelope {
    ctl e, env, keep, take;
    ctl step(float dec, float base)
    {
        e *= (ctl)dec;
        env = env * keep + (e + (ctl)base) * take;
        return env;
    }
};

struct Filter {
    real y1, y2;
    real step(float x, const float* c)
    {
        real c0 = (real)c[0], c1 = (real)c[1], c2 = (real)c[2];
        real y = ((real)x * c2 + c0 * y1) - c1 * y2;
        y2 = y1;
        y1 = y;
        return y;
    }
};

}  // namespace

// pcf::run: the 16 groups of a block.
static void run(Block& bus, const Tables& t, uint32_t row, CoefCache& cc, bool bandpass,
                Envelope& env, Filter& f, float dec, float base)
{
    for (int g = 0; g < BLOCK / 4; g++) {
        const float* c = t.pcf_coef(bandpass, row, (uint32_t)env_index(env.step(dec, base)), cc);
        for (int k = 4 * g; k < 4 * g + 4; k++) {
            real prev = f.y1;
            real y = f.step(bus[k], c);
            bus[k] = st(bandpass ? y - prev : y);
        }
    }
}

// The meter update 0x10016664.
static void meter_update(Pcf& p)
{
    if ((int32_t)bits(p.peak) > (int32_t)0x3F800000)
        p.params[Pcf::METER] = 0x7F;
    else
        p.params[Pcf::METER] = (uint8_t)as_i64((real)p.peak * (real)METER_SCALE);
    p.peak = st((real)p.peak * (real)METER_DECAY);
}

// Pcf::control: false when the length is 0 (the idiv at 0x10016811 faults).
static bool control(Pcf& pcf, const BlockContext& ctx, Envelope& out)
{
    uint8_t p[Pcf::PARAMS];
    memcpy(p, pcf.params, sizeof p);
    uint16_t len, res;
    pattern_of(p[Pcf::WAVE], &len, &res);
    int32_t q;
    if (quotient_of(ctx.tick, res, &q))
        pcf.quotient = q;
    else if (ctx.stack_word.some)
        pcf.quotient = ctx.stack_word.v;
    ctl s = smooth_cutoff(ctx.tables->pcf_smoother, p[Pcf::FREQUENCY], pcf.smooth[0], pcf.smooth[1]);
    pcf.smooth[1] = pcf.smooth[0];
    if (len == 0) return false;
    int32_t step = pcf.quotient % (int32_t)len;
    pcf.smooth[0] = st(s);
    pcf.base = st(s);
    ctl e = (ctl)pcf.trigger;
    ctl keep = (ctl)pcf.attack;
    ctl take = ONE - (ctl)pcf.attack;
    if (step != pcf.step) {
        pcf.step = step;
        uint32_t d = (uint32_t)(p[Pcf::DECAY] >> 3);
        pcf.decay = PCF_DECAY[d < 15 ? d : 15];
        uint8_t v = velocity(p[Pcf::WAVE], step);
        if (v != 0) {
            e = trigger_level(v, p[Pcf::AMOUNT], pcf.base);
            if (v & 1) {
                pcf.attack = SLOW_KEEP;
                keep = (ctl)SLOW_KEEP;
                take = (ctl)SLOW_TAKE;
            } else {
                pcf.attack = 0.0f;
                keep = (ctl)ZERO;
                take = (ctl)INSTANT_TAKE;
            }
        }
    }
    out.e = e;
    out.env = (ctl)pcf.env;
    out.keep = keep;
    out.take = take;
    return true;
}

Pcf::Pcf()
    : counter(0), last_counter(0), trigger(0.0f), base(0.0f), env(0.0f), step(-1), attack(0.0f),
      decay(0.0f), peak(0.0f), quotient(0), has_fault(false)
{
    memcpy(params, DEFAULTS, PARAMS);
    memcpy(pattern, DEFAULTS, PARAMS);
    lp[0] = lp[1] = 0.0f;
    bp[0] = bp[1] = 0.0f;
    smooth[0] = smooth[1] = 0.0f;
    fault.wave = 0;
}

const uint8_t* Pcf::live(uint32_t* len) const
{
    *len = PARAMS;
    return params;
}

void Pcf::set_song_mode(bool on)
{
    if (on)
        memcpy(pattern, params, PARAMS);
    else
        memcpy(params, pattern, PARAMS);
}

void Pcf::data(const uint8_t* payload, uint32_t len, bool song_mode)
{
    if (len < PARAMS) return;
    memcpy(pattern, payload, PARAMS);
    if (!song_mode) memcpy(params, pattern, PARAMS);
}

void Pcf::set_param(uint8_t ctrl, uint8_t value)
{
    if (ctrl <= MODE) params[ctrl] = value;
}

void Pcf::init_track(TrackMut& track)
{
    for (int c = 0; c <= MODE; c++) track.insert(0, (uint8_t)c, pattern[c]);
}

OptI32 Pcf::stack_word(OptI32 prev) const
{
    uint16_t len, res;
    pattern_of(params[WAVE], &len, &res);
    int32_t q;
    if (params[ENABLED] != 0 && quotient_of(0, res, &q)) return OptI32::of(quotient);
    return prev;
}

void Pcf::process(Block& bus, const BlockContext& ctx)
{
    if (params[ENABLED] == 0) return;
    if ((counter & 15) == 0) meter_update(*this);
    counter = (uint16_t)(counter + 1u);
    float v = abs_bits(bus[ctx.meter_index]);
    if (v > peak) peak = v;
    Envelope e;
    if (!control(*this, ctx, e)) {
        has_fault = true;
        fault.wave = params[WAVE];
        return;
    }
    uint32_t row = ((uint32_t)params[RESONANCE] * 8u) >> 7;
    if (row > 7) row = 7;
    bool lowpass = params[MODE] == 1;
    const float* state = lowpass ? lp : bp;
    Filter f;
    f.y1 = (real)state[0];
    f.y2 = (real)state[1];
    run(bus, *ctx.tables, row, coef_cache, !lowpass, e, f, decay, base);
    float s0 = st(f.y1), s1 = st(f.y2);
    if (lowpass) {
        lp[0] = s0;
        lp[1] = s1;
        bp[0] = bp[1] = 0.0f;
    } else {
        bp[0] = s0;
        bp[1] = s1;
        lp[0] = lp[1] = 0.0f;
    }
    trigger = st(e.e);
    env = st(e.env);
}

void Pcf::update(const BlockContext& ctx)
{
    (void)ctx;
    if (counter == last_counter) params[METER] = 0;
    last_counter = counter;
}

bool Pcf::faulted(Fault* f)
{
    if (!has_fault) return false;
    if (f) *f = fault;
    has_fault = false;
    return true;
}

